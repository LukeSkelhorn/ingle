CREATE TABLE chores (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    household_id      bigint NOT NULL REFERENCES households (id) ON DELETE CASCADE,
    title             text   NOT NULL CHECK (length(title) BETWEEN 1 AND 100),
    description       text   NOT NULL DEFAULT '',
    mode              text   NOT NULL CHECK (mode IN ('assigned', 'pool', 'shared', 'each')),
    assignee_id       bigint REFERENCES people (id) ON DELETE RESTRICT,
    rrule             text,
    starts_on         text   NOT NULL CHECK (starts_on ~ '^\d{4}-\d{2}-\d{2}$' AND pg_input_is_valid(starts_on, 'date')),
    points            bigint NOT NULL DEFAULT 0 CHECK (points >= 0),
    pence             bigint NOT NULL DEFAULT 0 CHECK (pence >= 0),
    requires_approval bigint NOT NULL DEFAULT 0 CHECK (requires_approval IN (0, 1)),
    archived_at       bigint,
    created_at        bigint NOT NULL,
    updated_at        bigint NOT NULL,
    emoji             text   NOT NULL DEFAULT '' CHECK (length(emoji) <= 16),
    day_mode          text   NOT NULL DEFAULT 'each' CHECK (day_mode IN ('each', 'any')),
    on_the_day        bigint NOT NULL DEFAULT 0 CHECK (on_the_day IN (0, 1)),
    due_times         text   NOT NULL DEFAULT '',
    show_before       bigint CHECK (show_before IS NULL OR show_before IN (30, 60, 120)),
    for_everyone      bigint NOT NULL DEFAULT 0 CHECK (for_everyone IN (0, 1)),
    adult_points      bigint NOT NULL DEFAULT 0 CHECK (adult_points >= 0),
    CHECK ((mode = 'assigned') = (assignee_id IS NOT NULL))
);
CREATE INDEX chores_household_idx ON chores (household_id);

CREATE TABLE chore_occurrences (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    household_id   bigint NOT NULL REFERENCES households (id) ON DELETE CASCADE,
    chore_id       bigint NOT NULL REFERENCES chores (id) ON DELETE CASCADE,
    due_on         text   NOT NULL CHECK (due_on ~ '^\d{4}-\d{2}-\d{2}$' AND pg_input_is_valid(due_on, 'date')),
    assignee_id    bigint REFERENCES people (id) ON DELETE RESTRICT,
    claimed_by     bigint REFERENCES people (id) ON DELETE RESTRICT,
    claimed_at     bigint,
    status         text   NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'claimed', 'done', 'skipped')),
    available_from text   CHECK (
        available_from IS NULL OR (
            available_from ~ '^\d{4}-\d{2}-\d{2}$' AND pg_input_is_valid(available_from, 'date')
            AND available_from <= due_on)
    ),
    due_time       text   NOT NULL DEFAULT '' CHECK (due_time = '' OR due_time ~ '^([01][0-9]|2[0-3]):[0-5][0-9]$'),
    for_person     bigint NOT NULL DEFAULT 0,
    UNIQUE (chore_id, due_on, due_time, for_person),
    CHECK (assignee_id IS NULL OR claimed_by IS NULL)
);
CREATE INDEX chore_occurrences_board_idx ON chore_occurrences (household_id, due_on);

CREATE TABLE completions (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    household_id  bigint NOT NULL REFERENCES households (id) ON DELETE CASCADE,
    occurrence_id bigint NOT NULL REFERENCES chore_occurrences (id) ON DELETE CASCADE,
    person_id     bigint NOT NULL REFERENCES people (id) ON DELETE RESTRICT,
    completed_at  bigint NOT NULL,
    status        text   NOT NULL CHECK (status IN ('pending', 'approved', 'rejected')),
    reviewed_by   bigint REFERENCES people (id) ON DELETE RESTRICT,
    reviewed_at   bigint,
    points        bigint NOT NULL CHECK (points >= 0),
    pence         bigint NOT NULL CHECK (pence >= 0)
);
CREATE INDEX completions_household_status_idx ON completions (household_id, status);
CREATE UNIQUE INDEX completions_live_occurrence_idx ON completions (occurrence_id) WHERE status <> 'rejected';

CREATE TABLE redemptions (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    household_id bigint NOT NULL REFERENCES households (id) ON DELETE CASCADE,
    reward_id    bigint NOT NULL REFERENCES rewards (id) ON DELETE RESTRICT,
    person_id    bigint NOT NULL REFERENCES people (id) ON DELETE RESTRICT,
    points       bigint NOT NULL CHECK (points >= 0),
    pence        bigint NOT NULL CHECK (pence >= 0),
    status       text   NOT NULL CHECK (status IN ('pending', 'approved', 'rejected')),
    requested_at bigint NOT NULL,
    reviewed_by  bigint REFERENCES people (id) ON DELETE RESTRICT,
    reviewed_at  bigint
);
CREATE INDEX redemptions_household_status_idx ON redemptions (household_id, status);

CREATE TABLE ledger_entries (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    household_id  bigint NOT NULL REFERENCES households (id) ON DELETE CASCADE,
    person_id     bigint NOT NULL REFERENCES people (id) ON DELETE RESTRICT,
    points        bigint NOT NULL,
    pence         bigint NOT NULL,
    kind          text   NOT NULL CHECK (kind IN ('completion', 'redemption', 'adjustment', 'payout', 'manual')),
    completion_id bigint UNIQUE REFERENCES completions (id) ON DELETE RESTRICT,
    redemption_id bigint UNIQUE REFERENCES redemptions (id) ON DELETE RESTRICT,
    note          text   NOT NULL DEFAULT '',
    created_by    bigint REFERENCES people (id) ON DELETE RESTRICT,
    created_at    bigint NOT NULL
);
CREATE INDEX ledger_entries_person_idx ON ledger_entries (person_id);

CREATE TABLE activity (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    household_id bigint NOT NULL REFERENCES households (id) ON DELETE CASCADE,
    actor_id     bigint REFERENCES people (id) ON DELETE SET NULL,
    verb         text   NOT NULL,
    subject_type text   NOT NULL,
    subject_id   bigint NOT NULL,
    data         text   CHECK (data IS NULL OR pg_input_is_valid(data, 'jsonb')),
    created_at   bigint NOT NULL
);
CREATE INDEX activity_household_created_idx ON activity (household_id, created_at DESC);

CREATE TABLE household_settings (
    household_id             bigint PRIMARY KEY REFERENCES households (id) ON DELETE CASCADE,
    timezone                 text   NOT NULL,
    day_starts_at            text   NOT NULL DEFAULT '00:00' CHECK (day_starts_at ~ '^([01][0-9]|2[0-3]):[0-5][0-9]$'),
    admin_idle_minutes       bigint NOT NULL DEFAULT 2 CHECK (admin_idle_minutes BETWEEN 1 AND 60),
    updated_at               bigint NOT NULL,
    screensaver_idle_minutes bigint NOT NULL DEFAULT 5 CHECK (screensaver_idle_minutes BETWEEN 0 AND 120),
    unlock_code_hash         text,
    lock_days                bigint NOT NULL DEFAULT 0 CHECK (lock_days BETWEEN 0 AND 127),
    lock_from                text   NOT NULL DEFAULT '09:00' CHECK (lock_from ~ '^([01][0-9]|2[0-3]):[0-5][0-9]$'),
    lock_until               text   NOT NULL DEFAULT '15:00' CHECK (lock_until ~ '^([01][0-9]|2[0-3]):[0-5][0-9]$'),
    lock_idle_hours          bigint NOT NULL DEFAULT 0 CHECK (lock_idle_hours BETWEEN 0 AND 72),
    unlock_code_length       bigint CHECK (unlock_code_length IS NULL OR unlock_code_length BETWEEN 4 AND 6),
    calendar_idle_minutes    bigint NOT NULL DEFAULT 2 CHECK (calendar_idle_minutes BETWEEN 0 AND 60)
);

CREATE TABLE devices (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    household_id bigint NOT NULL REFERENCES households (id) ON DELETE CASCADE,
    name         text   NOT NULL CHECK (length(name) BETWEEN 1 AND 50),
    token_hash   bytea  NOT NULL UNIQUE,
    created_by   bigint REFERENCES people (id) ON DELETE SET NULL,
    created_at   bigint NOT NULL,
    last_seen_at bigint NOT NULL,
    revoked_at   bigint
);
CREATE INDEX devices_household_idx ON devices (household_id);

CREATE TABLE sessions (
    token_hash   bytea  PRIMARY KEY,
    household_id bigint NOT NULL REFERENCES households (id) ON DELETE CASCADE,
    person_id    bigint NOT NULL REFERENCES people (id) ON DELETE CASCADE,
    kind         text   NOT NULL CHECK (kind IN ('display', 'personal')),
    device_id    bigint REFERENCES devices (id) ON DELETE CASCADE,
    user_agent   text   NOT NULL DEFAULT '',
    created_at   bigint NOT NULL,
    last_seen_at bigint NOT NULL,
    CHECK ((kind = 'display') = (device_id IS NOT NULL))
);
CREATE INDEX sessions_person_idx ON sessions (person_id);

CREATE TABLE photos (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    cost_pence   bigint NOT NULL DEFAULT 0 CHECK (cost_pence >= 0),
    archived_at  bigint,
    created_at   bigint NOT NULL,
    emoji        text   NOT NULL DEFAULT '' CHECK (length(emoji) <= 16)
);
CREATE INDEX rewards_household_idx ON rewards (household_id);

